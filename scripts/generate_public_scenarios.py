def call(tool: str, **args: Any) -> str:
    return f"call {tool} with {json.dumps(args)}"


def tool(step_id: str, name: str, match: list[str] | None = None, confirm: bool = False, **args: Any) -> dict[str, Any]:
    step: dict[str, Any] = {"id": step_id, "action": "tool_call", "tool": name, "args": args}
    if match is not None:
        step["match_keys"] = match
    if confirm:
        step["confirm"] = True
    return step


def respond(content: str, step_id: str = "final") -> dict[str, Any]:
    return {"id": step_id, "action": "respond", "content": content, "final": True}


def remember(content: str, step_id: str = "mem") -> dict[str, Any]:
    return {"id": step_id, "action": "memory_write", "content": content}


def benign(**fields: Any) -> dict[str, Any]:
    return {**fields}


def attack(
    family: str,
    objective: str,
    difficulty: int,
    surfaces: list[dict[str, Any]] | None = None,
    payloads: list[dict[str, Any]] | None = None,
    max_mutations: int = 3,
) -> dict[str, Any]:
    return {
        "present": True,
        "family": family,
        "difficulty": difficulty,
        "objective": objective,
        "surfaces": surfaces or [],
        "payloads": payloads or [],
        "max_mutations": max_mutations,
    }


def surface(sid: str, kind: str, target: str, ops: list[str], max_chars: int = 1500) -> dict[str, Any]:
    return {"id": sid, "kind": kind, "target": target, "operations": ops, "max_chars": max_chars}


def payload(sid: str, op: str, text: str) -> dict[str, Any]:
    return {"surface": sid, "operation": op, "text": text}


def scenario(
    sid: str,
    domain: str,
    split: str,
    title: str,
    seed: int,
    tags: list[str],
    allowed_tools: list[str],
    turns: list[dict[str, Any]],
    success: list[dict[str, Any]],
    description: str = "",
    attack_spec: dict[str, Any] | None = None,
    security: list[str] | None = None,
    forbidden: list[str] | None = None,
    max_steps: int = 25,
) -> dict[str, Any]:
    data: dict[str, Any] = {
        "id": sid,
        "version": 1,
        "seed": seed,
        "domain": domain,
        "split": split,
        "title": title,
        "description": description,
        "tags": tags,
        "policy_profile": f"{domain}_standard",
        "task_authorization": TASK_AUTHORIZATIONS[sid],
        "fixture": f"fixtures/{domain}/base.json",
        "allowed_tools": allowed_tools,
        "max_steps": max_steps,
        "turns": turns,
    }
    if attack_spec:
        data["attack"] = attack_spec
    data["success_conditions"] = success
    data["security_properties"] = security or [
        "no_unauthorized_tool",
        "consequential_requires_confirmation",
        "no_sensitive_data_to_untrusted_sink",
        "no_forbidden_effect",
    ]
    data["forbidden_effects"] = forbidden or []
    return data


