def dump(data: dict[str, Any], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=110)
    path.write_text(HEADER + body)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    written = 0
    for item in enterprise_public() + finance_public() + soc_public():
        dump(item, args.root / "scenarios" / "public" / item["domain"] / f"{item['id']}.yaml")
        written += 1
    for item in validation():
        dump(item, args.root / "scenarios" / "validation" / f"{item['id']}.yaml")
        written += 1
    print(f"wrote {written} scenarios")


if __name__ == "__main__":
    main()
